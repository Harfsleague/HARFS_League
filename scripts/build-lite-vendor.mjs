// Builds css/lite-vendor.css — the two big CDN stylesheets (Tailwind 2.2.19 + Font Awesome 6.0.0-beta3) shrunk to what the
// app actually uses, with Font Awesome's solid font embedded, so the lite file needs NO internet at all.
//
//   cd <repo>            (needs Node 18+)
//   npm i --no-save purgecss tailwindcss@2.2.19 @fortawesome/fontawesome-free@6.0.0-beta3
//   node scripts/build-lite-vendor.mjs
//
// Re-run it whenever you start using new Tailwind classes or new icons in index.html / js/*.js.
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { PurgeCSS } = require('purgecss');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const tw = require.resolve('tailwindcss/dist/tailwind.min.css');
const faDir = path.dirname(require.resolve('@fortawesome/fontawesome-free/css/all.min.css'));
const content = [path.join(root, 'index.html'), ...fs.readdirSync(path.join(root, 'js')).filter(f=>f.endsWith('.js')).map(f=>path.join(root, 'js', f))];

// every class-looking token in the sources (Tailwind variants such as md:flex or hover:bg-x included)
const rawSources = content.map(raw => ({ raw: fs.readFileSync(raw, 'utf8'), extension: 'html' }));
const allText = rawSources.map(s => s.raw).join('\n');
const usedFaIcons = Array.from(new Set(allText.match(/\bfa-[a-z0-9-]+/g) || []));
const extractor = c => c.match(/[A-Za-z0-9_\-:\/\.\[\]%#!]+/g) || [];
const run = async (cssFile, safelist) => (await new PurgeCSS().purge({
    content: rawSources,
    css: [{ raw: fs.readFileSync(cssFile, 'utf8') }],
    defaultExtractor: extractor,
    safelist: { standard: safelist, deep: [], greedy: [] },
    keyframes: true, fontFace: false, variables: false,
}))[0].css;

let tailwind = await run(tw, []);
let fa = await run(path.join(faDir, 'all.min.css'), [/^fa$/, /^fas$/, /^far$/, /^fa-solid$/, /^fa-regular$/, /^fa-spin$/, /^fa-pulse$/, ...usedFaIcons]);
// Embed only fa-solid-900.woff2 (no brand icons are used, and the 4 regular icons exist in solid-900)
fa = fa.replace(/@font-face\{[^}]*\}/g, '').replace(/\.far,\.fa-regular\{font-weight:400\}/g, '.far,.fa-regular{font-weight:900}');
const face = (family, weight, file) => `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${fs.readFileSync(path.join(faDir, '..', 'webfonts', file)).toString('base64')}) format("woff2");}`;
const fonts = face('Font Awesome 6 Free', 900, 'fa-solid-900.woff2');
const out = `/* GENERATED by scripts/build-lite-vendor.mjs — do not edit. Tailwind 2.2.19 (purged) + Font Awesome 6.0.0-beta3 (purged, fonts embedded). */\n${tailwind}\n${fonts}\n${fa}.far,.fa-regular{font-family:"Font Awesome 6 Free";font-weight:900}\n`;
fs.writeFileSync(path.join(root, 'css', 'lite-vendor.css'), out);
console.log('css/lite-vendor.css', (out.length / 1024).toFixed(0) + ' KB  (tailwind ' + (tailwind.length / 1024).toFixed(0) + ' KB, font awesome ' + (fa.length / 1024).toFixed(0) + ' KB + fonts)');
